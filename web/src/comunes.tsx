export function TituloPantalla({ titulo, children }: { titulo: string; children?: ReactNode }) {
  return (
    <div className="titulo-pantalla">
      <h1>{titulo}</h1>
      {children}
    </div>
  )
}

export function Pastilla(p: {
  texto: string
  onClick: () => void
  icono?: NombreIcono
  iconoFinal?: NombreIcono
  punto?: string
  destacada?: boolean
  chica?: boolean
  disabled?: boolean
}) {
  return (
    <button
      className={`pastilla${p.destacada ? ' destacada' : ''}${p.chica ? ' chica' : ''}`}
      onClick={p.onClick}
      disabled={p.disabled}
    >
      {p.punto && <span className="punto" style={{ background: p.punto }} />}
      {p.icono && <Icono n={p.icono} tam={18} />}
      {p.texto}
      {p.iconoFinal && <Icono n={p.iconoFinal} tam={18} />}
    </button>
  )
}

export function Etiqueta({ texto, color, fondo }: { texto: string; color: string; fondo?: string }) {
  return (
    <span className="etiqueta" style={{ color, background: fondo ?? `color-mix(in srgb, ${color} 16%, transparent)` }}>
      {texto}
    </span>
  )
}

export function Modal({ onCerrar, children }: { onCerrar: () => void; children: ReactNode }) {
  return (
    <div className="velo" onClick={onCerrar}>
      <div className="modal" onClick={(e) => e.stopPropagation()} role="dialog" aria-modal>
        {children}
      </div>
    </div>
  )
}

/** Logo de la universidad sobre un cuadro blanco; si no hay logo (o no carga), sus siglas. */
export function LogoUniversidad({ u, tam = 48 }: { u: Pick<Universidad, 'nombre' | 'siglas' | 'logo_url'> | null | undefined; tam?: number }) {
  const [fallo, setFallo] = useState(false)
  const siglas = u?.siglas ?? u?.nombre.slice(0, 4) ?? '🎓'
  return (
    <span className="logo-uni" style={{ width: tam, height: tam, borderRadius: Math.round(tam * 0.27), fontSize: tam * (siglas.length > 3 ? 0.24 : 0.32) }}>
      {u?.logo_url && !fallo
        ? <img src={u.logo_url} alt={siglas} loading="lazy" onError={() => setFallo(true)} />
        : siglas}
    </span>
  )
}

